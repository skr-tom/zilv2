import java.io.FileInputStream
import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

// 可选：根目录存在 keystore.properties 时用它给 release 签名；不存在就统一用 debug 签名。
// 关键是「每次发版都用同一把签名」——签名变了就必须卸载重装，应用内更新会失败。
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties()
if (keystorePropertiesFile.exists()) {
    FileInputStream(keystorePropertiesFile).use { keystoreProperties.load(it) }
}

android {
    namespace = "com.zilu.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.zilu.app"
        minSdk = 26
        targetSdk = 35
        versionCode = 6
        versionName = "4.2.0"
        resourceConfigurations += listOf("zh", "en")
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("zilu") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // 不配 keystore.properties 时也用 debug 签名，保证和历史手动安装的包签名一致
            signingConfig = signingConfigs.findByName("zilu") ?: signingConfigs.getByName("debug")
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

